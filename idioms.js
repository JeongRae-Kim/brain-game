export function parseIdioms(text) {
  return String(text).split(/\r?\n/).map(s => s.trim()).filter(Boolean).map(s => {
    const i = s.search(/[:：]/);
    if (i < 0) return null;
    const head = s.slice(0, i).trim();
    const hm = head.match(/^([가-힣]+)\s*[(（]\s*([^)）]+?)\s*[)）]$/);
    return hm ? { w: hm[1], h: hm[2], m: s.slice(i + 1).trim() } : { w: head, m: s.slice(i + 1).trim() };
  }).filter(x => x && /^[가-힣]{2,8}$/.test(x.w) && x.m);
}

export const IDIOMS = Object.fromEntries(Object.entries(RAW).map(([k, v]) => [k, parseIdioms(v)]));

// ---------- 사자성어 크로스워드 ----------
import { rng, shuffle } from "./games.js";
import { buildCrossword, usable } from "./english.js";

export const IDIOM_MIN = 25;
const IDIOM_SIZE = { easy: { n: 9, target: 5, reveal: 1 }, mid: { n: 11, target: 7, reveal: 0.5 }, hard: { n: 13, target: 10, reveal: 0 } };

export function idiomList(level, custom) {
  const c = custom?.["idiom" + level];
  return c && c.length >= 10 ? c : (IDIOMS[level] || IDIOMS.easy);
}

export function makeIdiomCross(seed, level, opts) {
  const cfg = IDIOM_SIZE[level] || IDIOM_SIZE.easy;
  const list = usable(idiomList(level, opts?.custom), opts?.exclude, IDIOM_MIN);
  const pz = buildCrossword(seed, list, cfg.n, cfg.target);
  // 미리 채워 둘 글자: 초급은 단어마다 1글자, 중급은 절반의 단어에 1글자, 고급은 없음
  const rand = rng(seed + 7);
  const given = new Set();
  for (const e of shuffle(pz.entries, rand)) {
    if (rand() >= cfg.reveal) continue;
    const i = Math.floor(rand() * e.word.length);
    given.add((e.r + (e.down ? i : 0)) * pz.cols + e.c + (e.down ? 0 : i));
  }
  const chars = [...new Set(list.flatMap(x => [...x.w]))];
  const hanja = Object.fromEntries(list.filter(x => x.h).map(x => [x.w, x.h]));
  return { ...pz, given, chars, hanja };
}
